UPDATE quiz_bank_overrides
SET questions = (
  SELECT jsonb_agg(
    CASE
      WHEN q->>'q' ILIKE '%Экологическая проблематика%'
        OR (q->'opts')::text ILIKE '%Экологическая проблематика%'
      THEN q || jsonb_build_object('sourceText', 'Какие взаимоотношения с природой нужны человеку сейчас? Да просто необходим союз с природой.
Сегодня в моде бег трусцой, но раньше самыми полезными для здоровья и для духовной жизни человека считались длительные пешеходные прогулки. Чем дальние пешие прогулки отличаются от бега трусцой? Когда человек бежит, он волей или неволей должен думать о том, что у него под ногами, в это время он не размышляет. Во время же пеших прогулок он размышляет. Старинные петербургские парки были рассчитаны на работу мысли, а не только на движение ногами. Прогулки по паркам вызывали мысли о природе, о смерти, о бренности существования, о животных, о тех или иных событиях. Гуляющий имел «материал» для размышлений лирических и эмоциональных, для размышлений о своём детстве, о союзе с природой, <...> так популярны были «романтические» парки, в которых природа находится в союзе с человеком.
В романтических парках человек только слегка вмешивается в природу, улучшая её, вот почему романтические парки жизненно необходимы современным городам. Мы устали от городской суеты, от непрекращающегося шума, преобладания техники и человека над природой; природа нами усиленно портится, и именно в романтических парках заключён идеальный союз с природой. 
(По Д. С. Лихачёву)')
      ELSE q
    END
    ORDER BY ord
  )
  FROM jsonb_array_elements(questions) WITH ORDINALITY AS x(q, ord)
),
updated_at = now()
WHERE task_n = 3;

