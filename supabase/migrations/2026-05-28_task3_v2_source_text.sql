-- («Какова роль парков и садов…», текст Лихачёва) в QUIZ_BANK[3] пустое
-- sourceText. В редакторе банка через UI поле не подцеплялось — формат
-- старого вопроса был без sourceText. Найдём вопрос по уникальной фразе
-- из его опций («Экологическая проблематика») и проставим sourceText.
-- Идемпотентно: повторный запуск не задвоит текст.
