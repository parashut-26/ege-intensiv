-- =============================================================================
-- Прецедент: Ольга смотрит модалку «📝 Список вопросов» по игре, и парсер не
-- может вытащить все детали (формат у игр разный, некоторые поля скрыты в
-- HTML-разметке). Хочет сама дописать заметку «вот тут такие вопросы, такие
-- фразеологизмы» — чтобы при следующем открытии не разбираться заново.
--
-- Поле:
--   teacher_notes text  — произвольный текст, доступен только учителю
--                         (в RLS у нас уже есть проверка на role='teacher'
--                         для PATCH /games).
-- =============================================================================

ALTER TABLE games
ADD COLUMN IF NOT EXISTS teacher_notes text;

COMMENT ON COLUMN games.teacher_notes IS
'Свободная заметка учителя к игре — что внутри, ключевые вопросы, на что обратить внимание. Виден только в модалке «Список вопросов» в учительском режиме.';
