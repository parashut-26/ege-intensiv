-- 2026-05-22: Чистим формулировки заданий 21 и 22 во всех загруженных вариантах
-- от мусора, который остался от парсера импорта PDF/Word.
--
-- Что чистим:
--
-- 1) Задание 21: всё, что начинается с фразы «Установите соответствие…» — это уже
--    начало задания 22, оно не должно быть в формулировке 21.
--    Также режем хвостовые цифры-ключи (вида «259 22 22 из 26»).
--
-- 2) Задание 22: всё, что начинается с «Прочитайте текст и выполните задания 23-26»
--    (или «23–26», «23 - 26») — это начало большого исходного текста для 23-26,
--    оно не должно быть в формулировке 22.
--    Также режем хвостовые цифры-ключи.
--
-- Запускать в Supabase Dashboard → SQL Editor → New query → Run.
-- Идемпотентно (если уже почищено — ничего не сломается).

-- =====================================================================
-- 1. Задание 21: режем «Установите соответствие …»
-- =====================================================================
update public.test_variant_questions
set question_text = regexp_replace(question_text,
  '\s*Установите\s+соответствие[\s\S]*$',
  '', 'g')
where num = 21
  and question_text ~ 'Установите\s+соответствие';

-- =====================================================================
-- 2. Задание 22: режем «Прочитайте текст и выполните задания 23(–|-|−)26»
-- =====================================================================
update public.test_variant_questions
set question_text = regexp_replace(question_text,
  '\s*Прочитайте\s+текст\s+и\s+выполните\s+задания\s*23\s*[–—−\-]\s*26[\s\S]*$',
  '', 'g')
where num = 22
  and question_text ~ 'Прочитайте\s+текст\s+и\s+выполните\s+задания\s*23';

-- =====================================================================
-- 3. Удаляем хвостовые цифровые «ключи» (типа «259 22 22 из 26», «12345»),
--    которые иногда прилипают к формулировке. Только если они в конце,
--    после пустой строки. И не трогаем многозначные числа внутри текста.
-- =====================================================================
update public.test_variant_questions
set question_text = regexp_replace(question_text,
  E'\\n+\\s*\\d{2,}[\\s\\d]*\\s*(из\\s+\\d+)?\\s*$',
  '', 'g')
where num in (21, 22)
  and question_text ~ E'\\n+\\s*\\d{2,}[\\s\\d]*\\s*(из\\s+\\d+)?\\s*$';

-- =====================================================================
-- 4. Trim trailing whitespace
-- =====================================================================
update public.test_variant_questions
set question_text = trim(both ' '||E'\n' from question_text)
where num in (21, 22)
  and question_text != trim(both ' '||E'\n' from question_text);

