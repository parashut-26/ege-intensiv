-- 2026-05-21: Универсальная очистка данных в test_variant_questions
--
-- Решаем 2 проблемы во всех уже загруженных вариантах:
--
-- 1) Альтернативные правильные ответы записаны как «вследствие<или>ввиду»,
--    а calcQuestionPoints/решалка понимает только «вследствие/ввиду».
--    Заменяем во всех строках.
--
-- 2) Формулировки заданий выглядят как одна простыня без абзацев — у
--    учителя в редакторе и у ученика всё сливается. Вставляем разделители
--    абзацев (двойной перенос строки) в типовых местах:
--    - перед каждой нумерованной опцией:    « 1)»,  « 2)», ...
--    - перед каждой буквенной опцией:       « А)», « Б)», « В)», ...
--    - между обычными предложениями (".  Заглавная") — это и есть основной
--      случай: 5 фраз для №5, инструкции типа «Запишите ...» в начале и пр.
--
-- Запускать в Supabase Dashboard → SQL Editor → New query → Run.
-- Идемпотентно (повторный запуск ничего не сломает — двойные переносы уже
-- проверяются регэкспом и не дублируются).

-- =====================================================================
-- 1. <или> → / в correct_answer
-- =====================================================================
update public.test_variant_questions
set correct_answer = replace(correct_answer, '<или>', '/')
where correct_answer like '%<или>%';

-- =====================================================================
-- 2a. Перед нумерованными опциями: пробел+«1)» / «2)» / ... → перенос строки
--    Только если перед ними не сразу \n (избегаем двойного применения)
-- =====================================================================
update public.test_variant_questions
set question_text = regexp_replace(
  question_text,
  '([^\s>])\s+([1-9]\))',
  E'\\1\n\n\\2',
  'g'
)
where question_text ~ '[^\s>]\s+[1-9]\)';

-- =====================================================================
-- 2b. Перед буквенными опциями (А), Б), В), Г), Д), Е))
-- =====================================================================
update public.test_variant_questions
set question_text = regexp_replace(
  question_text,
  '([^\s>])\s+([А-ЕЁ]\))',
  E'\\1\n\n\\2',
  'g'
)
where question_text ~ '[^\s>]\s+[А-ЕЁ]\)';

-- =====================================================================
-- 2c. Перед каждым новым предложением: «.  Заглавная» / «!  Заглавная» / «?  Заглавная»
--    Это основная регулярка — разбивает простыню на нормальные абзацы.
--    Условие: между «.» и заглавной — хотя бы один пробел (без переноса).
-- =====================================================================
update public.test_variant_questions
set question_text = regexp_replace(
  question_text,
  '([.!?])\s+([А-ЯЁ])',
  E'\\1\n\n\\2',
  'g'
)
where question_text ~ '[.!?][[:space:]]+[А-ЯЁ]';

-- =====================================================================
-- 3. То же самое для пояснений (explanation) — там тоже могут быть простыни
-- =====================================================================
update public.test_variant_questions
set explanation = regexp_replace(
  explanation,
  '([.!?])\s+([А-ЯЁ])',
  E'\\1\n\n\\2',
  'g'
)
where explanation is not null
  and explanation ~ '[.!?][[:space:]]+[А-ЯЁ]';

-- =====================================================================
-- 4. И для исходных текстов (test_variant_source_texts) — на всякий случай
--    Здесь обычно уже есть разметка, но проверим.
-- =====================================================================
update public.test_variant_source_texts
set body = regexp_replace(
  body,
  '([.!?])\s+(\(\d+\))',
  E'\\1\n\n\\2',
  'g'
)
where body ~ '[.!?][[:space:]]+\(\d+\)';

