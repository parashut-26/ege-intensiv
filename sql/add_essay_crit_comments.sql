-- =========================================================
-- ИНДИВИДУАЛЬНЫЕ ПОЯСНЕНИЯ УЧИТЕЛЯ ПО КРИТЕРИЯМ К1–К10
--
-- Зачем: часто балл снижают по К1–К6 (содержание/речь) без выделений
-- в тексте, и ученику непонятно, ЗА ЧТО снят балл. Раньше был только
-- общий комментарий на всю работу. Теперь учитель может оставить
-- короткое пояснение под каждым критерием — ученик видит его в своём
-- результате прямо под этим критерием.
--
-- Храним одним JSONB-полем: { "K1": "...", "K3": "...", "K8": "..." }.
-- Ключи — id критерия в верхнем регистре, значения — текст. Пустые
-- значения фронтенд не присылает; если пояснений нет — пишется NULL.
--
-- RLS не трогаем: essay_reviews уже читается учеником в его кабинете
-- (балл/комментарий он и так видит) — новая колонка читается так же.
-- =========================================================

ALTER TABLE essay_reviews
  ADD COLUMN IF NOT EXISTS crit_comments JSONB;

-- Проверка
SELECT 'essay_reviews.crit_comments ok' AS status;
