-- =========================================================
-- ВИДИМЫЙ УЧЕНИКУ КОММЕНТАРИЙ УЧИТЕЛЯ
--
-- У profiles уже есть поле teacher_comment — ПРИВАТНОЕ, ученик его не видит.
-- Это черновики и заметки учителя для себя.
--
-- Добавляем второе поле student_visible_comment — ВИДИМЫЙ ученику.
-- Учитель пишет в нём, ученик читает в своём кабинете (вкладка «Достижения»).
--
-- RLS:
--   - Учитель/куратор: SELECT, UPDATE — могут читать и менять у любого ученика.
--   - Ученик: SELECT — может прочитать ТОЛЬКО СВОЙ.
--   - Все остальные — ничего.
--
-- Существующая политика profiles_self для SELECT (если есть) уже разрешает
-- ученику читать свою строку → значит, новая колонка автоматически читается.
-- =========================================================

ALTER TABLE profiles
  ADD COLUMN IF NOT EXISTS student_visible_comment TEXT;

SELECT 'profiles.student_visible_comment ok' AS status;
